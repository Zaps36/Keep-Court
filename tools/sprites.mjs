// --- helpers ---------------------------------------------------------------
/** Collected row-width problems, reported together by the generator. */
export const ROW_ERRORS = []

/** Build a row of exactly `width` chars from [char,count] pairs. */
function mkRow(width, pairs) {
  let s = ''
  for (const [ch, n] of pairs) s += ch.repeat(n)
  if (s.length !== width) {
    ROW_ERRORS.push(
      `width ${s.length} != ${width}: "${s}"  (from ${JSON.stringify(pairs)})`,
    )
    // Pad/trim so the module still loads and every error can be reported.
    s = s.length < width ? s + '.'.repeat(width - s.length) : s.slice(0, width)
  }
  return s
}
const R32 = (...pairs) => mkRow(32, pairs)
const R16 = (...pairs) => mkRow(16, pairs)
const EMPTY32 = '.'.repeat(32)

